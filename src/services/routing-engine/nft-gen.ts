// nftables fragment generator for the tier engine.
// Emitted file lands at /usr/share/nftables.d/ruleset-post/48-panel-tiers.nft
// and is loaded by fw4 on every ruleset build, so it survives reloads.
import { normalizeDomain, type TierConfig } from "./types";

export const NFT_TABLE = "paneltiers";
export const SET_TIER1 = "tier1"; // RU direct (dnsmasq nftset + curated CIDRs)
export const SET_TIER2 = "tier2"; // zapret-direct (dnsmasq nftset)
export const SET_PROXYX = "proxyx"; // forced-proxy statics (tier3 extras)
export const SET_NODEIP = "nodeip"; // VPN node server IPs (loop guard)

function hostOf(server: string): string {
  const s = String(server || "").trim().replace(/^\[|\]$/g, "");
  return /^\d+\.\d+\.\d+\.\d+$/.test(s) ? s : "";
}

function fmtCidrList(cidrs: string[], indent: string, wrapWidth = 56): string {
  const sorted = [...new Set(cidrs.map((c) => c.trim()).filter(Boolean))].sort();
  if (sorted.length === 0) return "";
  const lines: string[] = [];
  let cur: string[] = [];
  let len = 0;
  for (const c of sorted) {
    if (len + c.length + 2 > wrapWidth && cur.length) {
      lines.push(cur.join(", ") + ",");
      cur = [];
      len = 0;
    }
    cur.push(c);
    len += c.length + 2;
  }
  if (cur.length) lines.push(cur.join(", "));
  return "\n" + lines.map((l) => indent + "    " + l).join("\n");
}

export interface NftGenInput {
  cfg: TierConfig;
  /** node server hostnames/IPs (IP literals go into @nodeip) */
  nodeServers: string[];
  /** extra static proxy-mark CIDRs (poison ranges, pinned CF IPs, ...) */
  staticProxyCidrs?: string[];
}

export function genTierNft({ cfg, nodeServers, staticProxyCidrs = [] }: NftGenInput): string {
  const markShort = cfg.mark.replace(/^0x0*/, "").padStart(6, "0");
  const nodeIps = [...new Set(nodeServers.map(hostOf).filter(Boolean))].sort();
  // Hostname-based nodes: their resolved IPs are appended to @nodeip at runtime by
  // the router (tiers_commit + panel-tier-routes); literal IPs are embedded here.
  const proxyStatics = [...new Set(staticProxyCidrs.map((c) => c.trim()).filter(Boolean))].sort();
  const t2Statics = [...new Set((cfg.tier2.networks || []).map((c) => c.trim()).filter(Boolean))].sort();
  const t1Statics = [...new Set(cfg.tier1.networks.map((c) => c.trim()).filter(Boolean))].sort();

  const L: string[] = [];
  L.push("# orbix tier routing — generated by the panel, DO NOT EDIT BY HAND");
  L.push(`# tiers: L1 direct=tier1+tier1dyn (RU)  L2 zapret=tier2(+static)  L3 mark=${cfg.mark} table=${cfg.routeTable}`);
  L.push("");
  // Atomic-recreate preamble: reloads replace the table instead of appending
  // duplicate rule copies (the first bare declaration makes the delete legal
  // on a fresh router where the table does not exist yet).
  L.push(`table inet ${NFT_TABLE}`);
  L.push(`delete table inet ${NFT_TABLE}`);
  L.push(`table inet ${NFT_TABLE} {`);
  // Static interval sets (panel-owned CIDRs) and dynamic timeout sets (dnsmasq-owned /32s).
  // NOTE: this kernel rejects flags interval,dynamic — statics and dynamics MUST be separate sets.
  L.push(dynSet(SET_TIER1 + "dyn", "1d"));
  L.push(dynSet(SET_TIER2, "1d"));
  L.push(dynSet(SET_PROXYX + "dyn", "1d"));
  L.push(dynSet(SET_NODEIP, "23h", nodeIps));
  L.push(statSet(SET_TIER1, t1Statics));
  L.push(statSet(SET_TIER2 + "static", t2Statics));
  L.push(statSet(SET_PROXYX, proxyStatics));
  L.push("");
  L.push("    chain marktier {");
  L.push("        type filter hook prerouting priority mangle; policy accept;");
  L.push("");
  L.push("        # --- loop guard first: anything bound to a VPN node, to our own");
  L.push("        # TUN segment, to private space or DNS-in stays on main ---");
  L.push(`        ip daddr @${SET_NODEIP} counter return`);
  L.push(`        ip daddr ${cfg.tunAddr}/${cfg.tunPrefix} counter return`);
  L.push("        ip daddr 10.0.0.0/8 counter return");
  L.push("        ip daddr 100.64.0.0/10 counter return");
  L.push("        ip daddr 127.0.0.0/8 counter return");
  L.push("        ip daddr 169.254.0.0/16 counter return");
  L.push("        ip daddr 172.16.0.0/12 counter return");
  L.push("        ip daddr 192.168.0.0/16 counter return");
  L.push('        iifname != \"' + cfg.lanIf + '\" counter return');
  L.push("");
  L.push("        # --- L1 Direct: RU zone bypasses Zapret queues AND VPN ---");
  L.push(`        ip daddr @${SET_TIER1} counter return`);
  L.push(`        ip daddr @${SET_TIER1}dyn counter return`);
  L.push("");
  if (cfg.proxyEnabled) {
    L.push("        # --- forced proxy (DNS-poison ranges, pinned edges, tier3 domains) ---");
    if (proxyStatics.length) L.push(`        ip daddr @${SET_PROXYX} counter meta mark set 0x${markShort}`);
    L.push(`        ip daddr @${SET_PROXYX}dyn counter meta mark set 0x${markShort}`);
    L.push("");
    L.push("        # --- L2 Zapret: direct WAN via nfqws, never the VPN mark ---");
    L.push(`        ip daddr @${SET_TIER2} counter return`);
    if (t2Statics.length) L.push(`        ip daddr @${SET_TIER2}static counter return`);
    L.push("");
    L.push("        # --- L3 Proxy: catch-all (LAST rules of the chain) ---");
    L.push(`        meta l4proto { tcp, udp } th dport 443 counter meta mark set 0x${markShort}`);
    L.push(`        meta l4proto tcp th dport 80 counter meta mark set 0x${markShort}`);
  } else {
    L.push("        # --- proxy disabled: tier2 zapret domains return, nothing is marked ---");
    L.push(`        ip daddr @${SET_TIER2} counter return`);
    if (t2Statics.length) L.push(`        ip daddr @${SET_TIER2}static counter return`);
  }
  L.push("    }");
  L.push("}");
  L.push("");
  return L.join("\n");
}

function dynSet(name: string, timeout: string, elements: string[] = []): string {
  const L = [`    set ${name} {`, "        type ipv4_addr", "        flags dynamic,timeout", `        timeout ${timeout}`];
  if (elements.length) L.push(`        elements = {${fmtCidrList(elements, "    ")}}`);
  L.push("        }");
  return L.join("\n");
}

function statSet(name: string, cidrs: string[]): string {
  if (cidrs.length === 0) return "";
  return [`    set ${name} {`, "        type ipv4_addr", "        flags interval", `        elements = {${fmtCidrList(cidrs, "    ")}`, "        }", "        }"].join("\n");
}

/** dnsmasq addn_options snippet: resolved IPs land in the nft sets above. */
export function genDnsmasqTiers(cfg: TierConfig): string {
  const t2 = [...new Set(cfg.tier2.domains.map(normalizeDomain).filter(Boolean))].sort();
  const t3 = [...new Set(cfg.tier3ExtraDomains.map(normalizeDomain).filter(Boolean))].sort();
  const out: string[] = ["# orbix tier routing — dnsmasq dynamic sets", "# L1 TLD rules (dnsmasq auto-punycodes .рф and follows CNAME chains)"];
  // bare TLD matches the TLD itself and every subdomain (dnsmasq semantics)
  for (const tld of ["ru", "xn--p1ai", "su"]) out.push(`nftset=/${tld}/inet#${NFT_TABLE}#${SET_TIER1}dyn`);
  for (const d of [...cfg.tier1.domains.map(normalizeDomain), ...t3]) {
    if (!d) continue;
    const set = t3.includes(d) ? `${SET_PROXYX}dyn` : `${SET_TIER1}dyn`;
    out.push(`nftset=/${d}/inet#${NFT_TABLE}#${set}`);
  }
  out.push("# L2 Zapret-direct domains");
  for (const d of t2) out.push(`nftset=/${d}/inet#${NFT_TABLE}#${SET_TIER2}`);
  out.push("");
  return out.join("\n");
}

/** Self-healing iproute script (cron): policy table for the marked tier3. */
export function genIprouteScript(cfg: TierConfig): string {
  return [
    "#!/bin/sh",
    "# orbix tier routing — policy route self-heal (cron-safe, idempotent)",
    "# re-seed VPN node IPs (hostname nodes; firewall reload wipes runtime set elements)",
    "if nft list table inet " + NFT_TABLE + " >/dev/null 2>&1 && [ -f /etc/orbix/subscriptions.json ]; then",
    "    for h in $(jsonfilter -i /etc/orbix/subscriptions.json -e '@.nodes[*].server' 2>/dev/null); do",
    "        case \"$h\" in *[^0-9.]*) : ;; *) continue ;; esac",
    "        nslookup \"$h\" 127.0.0.1 2>/dev/null | grep -oE '([0-9]{1,3}\\.){3}[0-9]{1,3}' | grep -v '^127\\.' | while read -r nip; do",
    "            nft add element inet " + NFT_TABLE + " " + SET_NODEIP + " \"{ $nip }\" 2>/dev/null",
    "        done",
    "    done",
    "fi",

    `[ -e /sys/class/net/${cfg.tunIf} ] || exit 0`,
    `sysctl -w net.ipv4.conf.${cfg.tunIf}.rp_filter=2 >/dev/null 2>&1`,
    `ip rule show | grep -q "fwmark ${cfg.markMask}" || \\`,
    `    ip rule add fwmark ${cfg.markMask} priority ${cfg.rulePriority} table ${cfg.routeTable}`,
    `ip route replace default dev ${cfg.tunIf} table ${cfg.routeTable}`,
    `ip route show table ${cfg.routeTable} | grep -q "default dev ${cfg.tunIf}" || { \\`,
    `    ip route del table ${cfg.routeTable} 2>/dev/null; \\`,
    `    ip route replace default dev ${cfg.tunIf} table ${cfg.routeTable}; }`,
    "exit 0",
    "",
  ].join("\n");
}
